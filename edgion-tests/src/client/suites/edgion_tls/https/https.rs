// HTTPS Test suite
// Only tested in Gateway mode, uses /secure/ path prefix
//
// Required config files (in edgion-tests/integration/conf/):
// - EndpointSlice_edge_test-http.yaml         # HTTPS backend service (reuse HTTP backend)
// - Service_edge_test-http.yaml               # HTTPS service definition
// - HTTPRoute_edge_test-http.yaml             # HTTPS routing rules (Host: test.example.com, path: /secure/)
// - Gateway_edge_tls-terminate-gateway.yaml   # TLS termination Gateway config (listening port)
// - EdgionTls_edge_edge-tls.yaml              # TLS certificate config
// - Secret_edgion-test_edge-tls.yaml          # TLS certificate Secret
// - GatewayClass__public-gateway.yaml         # GatewayClass config
//
// Generated certificate files:
// - edgion-tests/certs/server.crt            # server certificate (generated by generate_certs.sh)
// - edgion-tests/certs/server.key            # server private key
// - edgion-tests/certs/ca.pem                # CA certificate

use crate::framework::{TestCase, TestContext, TestResult, TestSuite};
use async_trait::async_trait;
use std::time::{Duration, Instant};

pub struct HttpsTestSuite;

impl HttpsTestSuite {
    fn frontend_http2_policy_cases() -> Vec<TestCase> {
        // Read the shared fixture port inventory instead of duplicating ports.
        let ports: serde_json::Value = serde_json::from_str(include_str!(concat!(
            env!("CARGO_MANIFEST_DIR"),
            "/integration/conf/ports.json"
        )))
        .expect("committed port inventory must parse");
        let ports = &ports["suites"]["EdgionTls/https"];
        let mut cases = Vec::new();
        for (policy, port_key, negotiated_version) in [
            ("default", "https", reqwest::Version::HTTP_2),
            ("enabled", "https_enabled", reqwest::Version::HTTP_2),
            ("disabled", "https_disabled", reqwest::Version::HTTP_11),
        ] {
            let port = u16::try_from(ports[port_key].as_u64().expect("fixture port must exist"))
                .expect("fixture port must fit u16");
            for force_http1 in [false, true] {
                let expected = if force_http1 {
                    reqwest::Version::HTTP_11
                } else {
                    negotiated_version
                };
                let client_mode = if force_http1 { "forced_h1" } else { "negotiating" };
                cases.push(TestCase::new(
                    format!("https_http2_{policy}_{client_mode}"),
                    format!("ARCH-040: HTTPS {policy} policy, {client_mode} client"),
                    move |ctx: TestContext| {
                        Box::pin(async move {
                            let start = Instant::now();
                            let result: anyhow::Result<()> = async {
                                let host = ctx.http_host.as_deref().unwrap_or("test.example.com");
                                let mut addresses = tokio::time::timeout(
                                    Duration::from_secs(2),
                                    tokio::net::lookup_host((ctx.target_host.as_str(), port)),
                                )
                                .await??;
                                let address = addresses.next().ok_or_else(|| anyhow::anyhow!("No target address"))?;
                                let mut builder = reqwest::Client::builder()
                                    .no_proxy()
                                    .danger_accept_invalid_certs(true)
                                    .timeout(Duration::from_secs(5))
                                    .resolve(host, address);
                                if force_http1 {
                                    builder = builder.http1_only();
                                }
                                // The normal client offers h2 and HTTP/1.1 through ALPN.
                                // No prior knowledge: disabled must fall back to usable H1.
                                let response = builder
                                    .build()?
                                    .get(format!("https://{host}:{port}/secure/health"))
                                    .send()
                                    .await?;
                                anyhow::ensure!(response.status() == reqwest::StatusCode::OK, "Expected HTTP 200");
                                anyhow::ensure!(
                                    response.version() == expected,
                                    "Expected {expected:?}, got {:?}",
                                    response.version()
                                );
                                let body = response.text().await?;
                                anyhow::ensure!(
                                    body.contains("healthy") || body.contains("Path: /secure/health"),
                                    "Expected complete health response"
                                );
                                Ok(())
                            }
                            .await;
                            match result {
                                Ok(()) => {
                                    TestResult::passed_with_message(start.elapsed(), format!("Verified {expected:?}"))
                                }
                                Err(error) => {
                                    TestResult::failed(start.elapsed(), format!("HTTPS policy failed: {error:#}"))
                                }
                            }
                        })
                    },
                ));
            }
        }
        cases
    }

    fn test_https_secure_health() -> TestCase {
        TestCase::new(
            "https_secure_health",
            "Test HTTPS /secure/health endpoint",
            |ctx: TestContext| {
                Box::pin(async move {
                    let start = Instant::now();

                    // Build HTTPS URL - use http_host for proper SNI in Gateway mode
                    let host = ctx.http_host.as_deref().unwrap_or(&ctx.target_host);
                    let url = format!("https://{}:{}/secure/health", host, ctx.https_port);

                    let request = ctx.http_client.get(&url);

                    match request.send().await {
                        Ok(response) => {
                            let status = response.status();
                            match response.text().await {
                                Ok(body) => {
                                    // Test server returns request info at /secure/health
                                    // Accept both "healthy" and path info as success indicators
                                    if status.is_success()
                                        && (body.contains("healthy") || body.contains("Path: /secure/health"))
                                    {
                                        TestResult::passed_with_message(start.elapsed(), format!("Status: {}", status))
                                    } else {
                                        TestResult::failed(
                                            start.elapsed(),
                                            format!("Unexpected response. Status: {}, Body: {}", status, body),
                                        )
                                    }
                                }
                                Err(e) => {
                                    TestResult::failed(start.elapsed(), format!("Failed to read response body: {}", e))
                                }
                            }
                        }
                        Err(e) => TestResult::failed(start.elapsed(), format!("HTTPS request failed: {}", e)),
                    }
                })
            },
        )
    }

    fn test_https_secure_echo() -> TestCase {
        TestCase::new(
            "https_secure_echo",
            "Test HTTPS /secure/echo endpoint（GET request）",
            |ctx: TestContext| {
                Box::pin(async move {
                    let start = Instant::now();

                    // Use http_host for proper SNI in Gateway mode
                    let host = ctx.http_host.as_deref().unwrap_or(&ctx.target_host);
                    let url = format!("https://{}:{}/secure/echo", host, ctx.https_port);

                    let request = ctx.http_client.get(&url);

                    match request.send().await {
                        Ok(response) => {
                            let status = response.status();
                            if status.is_success() {
                                TestResult::passed_with_message(start.elapsed(), format!("Status: {}", status))
                            } else {
                                match response.text().await {
                                    Ok(body) => TestResult::failed(
                                        start.elapsed(),
                                        format!("Request failed. Status: {}, Body: {}", status, body),
                                    ),
                                    Err(e) => TestResult::failed(
                                        start.elapsed(),
                                        format!("Request failed. Status: {}, Error reading body: {}", status, e),
                                    ),
                                }
                            }
                        }
                        Err(e) => TestResult::failed(start.elapsed(), format!("HTTPS request failed: {}", e)),
                    }
                })
            },
        )
    }

    fn test_https_secure_status() -> TestCase {
        TestCase::new(
            "https_secure_status",
            "Test HTTPS /secure/status/200 endpoint",
            |ctx: TestContext| {
                Box::pin(async move {
                    let start = Instant::now();

                    // Use http_host for proper SNI in Gateway mode
                    let host = ctx.http_host.as_deref().unwrap_or(&ctx.target_host);
                    let url = format!("https://{}:{}/secure/status/200", host, ctx.https_port);

                    let request = ctx.http_client.get(&url);

                    match request.send().await {
                        Ok(response) => {
                            let status = response.status();
                            if status.as_u16() == 200 {
                                TestResult::passed_with_message(start.elapsed(), format!("Status code: {}", status))
                            } else {
                                TestResult::failed(start.elapsed(), format!("Expected 200, got {}", status))
                            }
                        }
                        Err(e) => TestResult::failed(start.elapsed(), format!("HTTPS request failed: {}", e)),
                    }
                })
            },
        )
    }
}

#[async_trait]
impl TestSuite for HttpsTestSuite {
    fn name(&self) -> &str {
        "HTTPS"
    }

    fn test_cases(&self) -> Vec<TestCase> {
        let mut cases = vec![
            Self::test_https_secure_health(),
            Self::test_https_secure_echo(),
            Self::test_https_secure_status(),
        ];
        cases.extend(Self::frontend_http2_policy_cases());
        cases
    }
}
